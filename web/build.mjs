#!/usr/bin/env node
/*
 * web/build.mjs - bake keret's own build modules into web/vendor/keret-core.js.
 *
 * The browser app runs the same src/*.js the CLI runs: this script reads those
 * files and emits them as CommonJS factories with a header recording what they
 * were made from, so test/web.test.js can tell when the bundle has drifted from
 * the sources it claims to embed (the same contract the source stamp gives a
 * committed dist/).
 *
 *   node web/build.mjs           write the bundle
 *   node web/build.mjs --check   fail if the bundle is stale, write nothing
 *
 * The assets (page.css, engine.js, the two Geist faces) are embedded too: the
 * app must build the wall without a single request, so it can run from a static
 * host - or from a file:// folder - with nothing else installed.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const OUT = path.join(HERE, 'vendor', 'keret-core.js');

/* Modules the browser needs, as module ids resolved from the virtual root. */
const SOURCES = [
  'gen.js',
  'src/config.js',
  'src/images.js',
  'src/layout.js',
  'src/page.js',
  'src/setup.js',
  'src/stamp.js',
];

/* Page furniture page.js reads at build time. */
const ASSETS = ['head.html', 'body.html', 'page.css', 'engine.js', 'ui.js'];

/* The wall carries its own type: the zip needs these bytes, and the social card
   needs the face as a data URI to render text inside an SVG. */
const FONTS = ['GeistMonoVF.woff2', 'GeistSansVF.woff2', 'LICENSE.txt'];

const sha = (buf) => createHash('sha256').update(buf).digest('hex');

function build() {
  const sources = {};
  const factories = [];

  for (const rel of SOURCES) {
    const id = '/' + rel;
    const buf = readFileSync(path.join(ROOT, rel));
    sources[rel] = sha(buf);
    // a hashbang is only legal on line 1 of a file; commented out here so stack
    // traces from the browser bundle still point at the right line
    const code = buf.toString('utf8').replace(/^#!/, '//');
    // The wrapper hands each module the node-shaped parameters it expects, so
    // the sources stay verbatim and nothing has to be rewritten to run them.
    factories.push('MODULES[' + JSON.stringify(id) + '] = function '
      + '(module, exports, require, __dirname, __filename, Buffer, process) {\n'
      + code + '\n};\n');
  }

  const assets = {};
  for (const name of ASSETS) {
    const buf = readFileSync(path.join(ROOT, 'src', 'assets', name));
    assets[name] = { hash: sha(buf), text: buf.toString('utf8') };
  }

  const fonts = {};
  for (const name of FONTS) {
    const buf = readFileSync(path.join(ROOT, 'src', 'assets', 'fonts', name));
    fonts[name] = { hash: sha(buf), base64: buf.toString('base64') };
  }

  const meta = {
    sources,
    assets: Object.fromEntries(Object.entries(assets).map(([k, v]) => [k, v.hash])),
    fonts: Object.fromEntries(Object.entries(fonts).map(([k, v]) => [k, v.hash])),
  };

  const header = '/* generated by web/build.mjs - do not edit by hand.\n'
    + ' *\n'
    + ' * keret\'s own build modules, embedded for the browser. Regenerate with\n'
    + ' * `npm run web:build`; test/web.test.js fails when this file no longer\n'
    + ' * matches the sources below.\n'
    + ' *\n'
    + Object.entries(meta.sources).map(([k, v]) => ' * ' + k.padEnd(16) + v.slice(0, 16)).join('\n')
    + '\n */\n';

  const body = [
    'export const META = ' + JSON.stringify(meta, null, 2) + ';\n',
    'export const MODULES = Object.create(null);\n',
    'export const ASSETS = ' + JSON.stringify(
      Object.fromEntries(Object.entries(assets).map(([k, v]) => [k, v.text])), null, 0) + ';\n',
    'export const FONTS = ' + JSON.stringify(
      Object.fromEntries(Object.entries(fonts).map(([k, v]) => [k, v.base64])), null, 0) + ';\n',
    ...factories,
  ].join('\n');

  return header + body;
}

const next = build();
const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';

if (process.argv.includes('--check')) {
  if (current !== next) {
    console.error('web/vendor/keret-core.js is stale - run `npm run web:build`');
    process.exit(1);
  }
  console.log('web bundle is in sync with src/');
  process.exit(0);
}

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, next);
console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + (next.length / 1024).toFixed(0) + ' KB)');
